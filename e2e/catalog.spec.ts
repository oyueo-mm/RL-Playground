import { test, expect } from '@playwright/test'
import { navigate, config } from './helpers'

test('random gallery moves four agents, replaces one card, previews and filters all 20 maps', async ({ page }, info) => {
  test.setTimeout(120000)
  await page.addInitScript(() => { Math.random = () => .999999 })
  await page.clock.install()
  let pausedAt = Date.now() + 10_000
  for (const [width,height] of info.project.name === 'mobile' ? [[390,844]] : [[1366,768],[1440,900],[1920,1080],[768,1024]]) {
    await page.setViewportSize({width,height});await page.goto('./')
    await page.getByRole('button',{name:'일시정지',exact:true}).click()
    // Freeze fake time: clock.install() otherwise keeps advancing with wall-clock time, so a slow
    // machine could rotate extra cards before runFor() below (reproduced by delaying 8 s).
    pausedAt += 100_000; await page.clock.pauseAt(pausedAt)
    const cards=page.locator('.mini-demo'),before=await cards.evaluateAll(nodes=>nodes.map(n=>({id:n.getAttribute('data-scenario'),step:Number(n.getAttribute('data-step'))})))
    expect(new Set(before.map(c=>c.id)).size).toBe(4)
    await page.getByRole('button',{name:'시연 재생',exact:true}).click()
    const positions=await cards.locator('[data-testid=agent-marker]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('cx')+','+n.getAttribute('cy')))
    await page.clock.runFor(650)
    for(let i=0;i<4;i++) {
      await expect(cards.nth(i)).toHaveAttribute('data-step',/^[1-9]\d*$/)
      const pos=await cards.nth(i).getByTestId('agent-marker').evaluate(n=>n.getAttribute('cx')+','+n.getAttribute('cy'))
      expect(pos).not.toBe(positions[i])
    }
    await page.clock.runFor(6000)
    await expect(cards.first()).not.toHaveAttribute('data-scenario',before[0].id!)
    for(let i=1;i<4;i++)await expect(cards.nth(i)).toHaveAttribute('data-scenario',before[i].id!)
    await page.getByRole('button',{name:'일시정지',exact:true}).click()
    await page.getByRole('button',{name:'맵 섞기'}).click();await page.getByRole('button',{name:'맵 섞기'}).click()
    const large=page.locator('.mini-demo[data-scenario="13_crossroads_expedition"]')
    await expect(large).toBeVisible()
    await expect(large.getByTestId('grid-svg')).toHaveAttribute('viewBox','0 0 800 800')
    if (width > 1100) await page.locator('.page-content').evaluate(el => el.scrollTo(0,0))
    await page.screenshot({animations:'disabled',path:info.outputPath(`catalog-home-${width}x${height}.png`)})
    await large.getByTestId('home-demo-grid').click()
    const modal=page.getByRole('dialog');await expect(modal).toBeVisible()
    await page.screenshot({animations:'disabled',path:info.outputPath(`catalog-preview-${width}x${height}.png`)})
    page.once('dialog',d=>d.dismiss());await modal.getByRole('button',{name:/이 맵으로 실험하기/}).click();await expect(modal).toBeVisible()
    await modal.getByRole('button',{name:'미리보기 닫기'}).click()
    await navigate(page,'presets')
    await expect(page.locator('.gallery-thumbnails > button')).toHaveCount(30)
    await page.locator('.gallery-filters summary').click()
    for(const difficulty of ['very-easy','easy','medium','hard','very-hard']){
      await page.getByLabel('난이도',{exact:true}).selectOption(difficulty)
      await expect(page.locator('.gallery-thumbnails > button')).toHaveCount(6)
    }
    await page.getByLabel('난이도',{exact:true}).selectOption('all')
    await page.getByTestId('preset-search').fill('Portal City')
    await expect(page.locator('.gallery-thumbnails > button')).toHaveCount(1)
    await expect(page.getByTestId('preset-14_portal_city')).toBeVisible()
    await page.getByTestId('preset-search').fill('')
    await page.screenshot({animations:'disabled',path:info.outputPath(`catalog-presets-${width}x${height}.png`)})
    await navigate(page,'guide')
    const resources=page.getByTestId('resources-0')
    await expect(resources.getByRole('link',{name:/강화학습 과목 소개/})).toBeVisible()
    await resources.getByRole('button',{name:'영어 무료',exact:true}).click();await expect(resources.getByRole('link',{name:/Introduction to Reinforcement Learning/})).toBeVisible()
    await resources.getByRole('button',{name:'이용 조건 확인'}).click();await expect(resources).toContainText('현재 접근 미검증')
    await page.screenshot({animations:'disabled',path:info.outputPath(`catalog-resources-${width}x${height}.png`)})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
    await navigate(page,'home');await page.getByRole('button',{name:'일시정지',exact:true}).click()
    await page.locator('.mini-demo').first().getByTestId('home-demo-grid').click()
    const accepted=page.getByRole('dialog')
    await accepted.getByRole('slider').focus();await page.keyboard.press('End')
    await expect(accepted.locator('[data-cell-kind=goal]')).toHaveCount(0)
    page.once('dialog',dialog=>dialog.accept());await accepted.getByRole('button',{name:/이 맵으로 실험하기/}).click()
    await expect(page.getByTestId('learning-grid')).toBeVisible()
    await expect(page.getByTestId('learning-grid').locator('[data-testid^=cell-]')).toHaveCount(64)
    await page.clock.resume()
  }
})

test('held keyboard and pointer movement stop on release blur pause restart and navigation', async ({page},info)=>{
  await page.goto('./');await navigate(page,'editor')
  const editor=page.getByTestId('env-editor')
  await editor.getByRole('button',{name:'속성 / 파일'}).click()
  await editor.getByTestId('env-editor-import-input').setInputFiles({name:'manual.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(config(12,12)))})
  await editor.getByRole('button',{name:'속성 닫기'}).click();await editor.getByTestId('manual-play-start').click()
  const play=page.getByTestId('manual-play'),progress=play.getByTestId('manual-progress')
  await page.clock.install();await page.keyboard.down('d');await page.clock.runFor(550);await page.keyboard.up('d')
  const steps=Number(await progress.getAttribute('data-steps'));expect(steps).toBeGreaterThanOrEqual(5)
  await page.clock.runFor(500);await expect(progress).toHaveAttribute('data-steps',String(steps))
  await page.keyboard.down('s');await page.clock.runFor(250);await page.evaluate(()=>window.dispatchEvent(new Event('blur')))
  const blurred=await progress.getAttribute('data-steps');await page.clock.runFor(500);await expect(progress).toHaveAttribute('data-steps',blurred!)
  await page.keyboard.up('s');await play.getByRole('button',{name:'다시 시작 (R)'}).click()
  const right=play.getByRole('button',{name:'오른쪽',exact:true});await right.hover();await page.mouse.down();await page.clock.runFor(450);await page.mouse.up()
  const pointer=await progress.getAttribute('data-steps');expect(Number(pointer)).toBeGreaterThanOrEqual(4)
  await page.clock.runFor(500);await expect(progress).toHaveAttribute('data-steps',pointer!)
  if(info.project.name==='mobile'){
    const cdp=await page.context().newCDPSession(page),box=(await right.boundingBox())!
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height/2,id:1}]})
    await page.clock.runFor(450)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]})
    const touched=await progress.getAttribute('data-steps');expect(Number(touched)).toBeGreaterThan(Number(pointer))
    await page.clock.runFor(500);await expect(progress).toHaveAttribute('data-steps',touched!);await cdp.detach()
  }
  await page.keyboard.down('d');await play.getByRole('button',{name:'일시정지',exact:true}).click()
  const paused=await progress.getAttribute('data-steps');await page.clock.runFor(600);await expect(progress).toHaveAttribute('data-steps',paused!)
  await page.keyboard.up('d');await play.getByRole('button',{name:'재개',exact:true}).click();await page.clock.runFor(400);await expect(progress).toHaveAttribute('data-steps',paused!)
  await page.screenshot({animations:'disabled',path:info.outputPath(`catalog-held-${info.project.name}.png`)})
  await page.keyboard.down('a');await navigate(page,'home');await page.clock.runFor(500);await page.keyboard.up('a');await navigate(page,'editor')
  const returned=await progress.getAttribute('data-steps');await page.clock.runFor(500);await expect(progress).toHaveAttribute('data-steps',returned!)
})
