test('cursor zoom, pan, editor-safe space drag, resize and mobile pinch',async({page},info)=>{
 page.on('dialog',d=>d.accept());await page.goto('./');await loadMap(page,config(32,20))
 const learning=page.getByTestId('learning-grid'),viewport=learning.getByTestId('grid-viewport'),drawing=learning.getByTestId('grid-stack')
 const area=(await viewport.boundingBox())!,point={x:area.x+area.width*.6,y:area.y+area.height*.6},before=(await drawing.boundingBox())!
 await page.mouse.move(point.x,point.y);await page.mouse.wheel(0,-120);await expect.poll(async()=>Number(await viewport.getAttribute('data-zoom'))).toBeGreaterThan(1)
 const after=(await drawing.boundingBox())!
 expect((point.x-after.x)/after.width).toBeCloseTo((point.x-before.x)/before.width,3)
 expect((point.y-after.y)/after.height).toBeCloseTo((point.y-before.y)/before.height,3)
 const pan=Number(await viewport.getAttribute('data-pan-x'))
 await page.mouse.move(point.x,point.y);await page.mouse.down();await page.mouse.move(point.x+45,point.y+20,{steps:4});await page.mouse.up()
 expect(Number(await viewport.getAttribute('data-pan-x'))).toBeCloseTo(pan+45)
 await learning.getByRole('button',{name:'Fit entire map'}).click();await expectFits(page)
 await page.getByTestId('toggle-analysis').click();const pane=page.getByTestId('analysis-panel'),handle=pane.getByRole('separator'),r=(await handle.boundingBox())!,old=(await pane.boundingBox())!
 await page.mouse.move(r.x+r.width/2,r.y+r.height/2);await page.mouse.down();await page.mouse.move(r.x+r.width/2-60,r.y+r.height/2-60,{steps:4});await page.mouse.up()
 const resized=(await pane.boundingBox())!;expect(info.project.name==='mobile'?resized.height:resized.width).toBeGreaterThan(info.project.name==='mobile'?old.height:old.width)
 await page.screenshot({animations:'disabled',path:info.outputPath(`upgrade30-resize-${info.project.name}.png`)})
 await pane.getByRole('button',{name:'분석 닫기'}).click();await navigate(page,'editor')
 const editor=page.getByTestId('env-editor'),ev=editor.getByTestId('grid-viewport'),eb=(await ev.boundingBox())!,x=eb.x+eb.width*.5,y=eb.y+eb.height*.5
 const oldWalls=await editor.locator('[data-cell-kind=wall]').count()
 await ev.focus();await page.keyboard.down('Space');await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+35,y+15,{steps:4});await page.mouse.up();await page.keyboard.up('Space')
 expect(await editor.locator('[data-cell-kind=wall]').count()).toBe(oldWalls);expect(Number(await ev.getAttribute('data-pan-x'))).toBeGreaterThan(0)
 if(info.project.name==='mobile'){
  await editor.getByRole('button',{name:'Fit entire map'}).click()
  const cdp=await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:x-25,y,id:1},{x:x+25,y,id:2}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-60,y,id:1},{x:x+60,y,id:2}]})
  await expect.poll(async()=>Number(await ev.getAttribute('data-zoom'))).toBeGreaterThan(1)
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});await cdp.detach()
  expect(await editor.locator('[data-cell-kind=wall]').count()).toBe(oldWalls)
 }
})

test('policy playback starts Normal, changes live and paused, restores training speed and permits repeats',async({page})=>{
 page.on('dialog',d=>d.accept());await page.clock.install();await page.goto('./')
 await loadMap(page,{...config(8,8),start:{x:0,y:7},goals:[{x:0,y:0}]})
 const slider=page.getByTestId('speed-slider');await slider.fill('100')
 await page.clock.pauseAt(await page.evaluate(()=>Date.now()+1000))
 await page.getByTestId('playback-run-greedy').click();await expect(slider).toBeEnabled();await expect(slider).toHaveValue('33')
 const marker=page.getByTestId('learning-grid').getByTestId('agent-marker'),first=await marker.getAttribute('cy')
 await slider.fill('30');await page.clock.runFor(200);await expect(marker).toHaveAttribute('cy',first!)
 await page.clock.runFor(40);expect(await marker.getAttribute('cy')).not.toBe(first)
 await page.getByTestId('playback-pause').click();const paused=await marker.getAttribute('cy');await slider.fill('60');await page.clock.runFor(1000);await expect(marker).toHaveAttribute('cy',paused!)
 await page.getByTestId('playback-resume').click();await expect(slider).toHaveValue('60')
 await page.getByTestId('playback-stop').click();await expect(slider).toHaveValue('100')
 await loadMap(page,config(8,8));await page.getByTestId('playback-run-greedy').click()
 await page.clock.runFor(3000);await expect(page.getByTestId('playback-stop')).toBeEnabled()
 await expect(page.locator('.policy-loop-notice')).toHaveCount(0)
 await page.getByTestId('playback-stop').click();await expect(slider).toHaveValue('100')
 await page.screenshot({animations:'disabled',path:test.info().outputPath('upgrade30-policy.png')})
})
