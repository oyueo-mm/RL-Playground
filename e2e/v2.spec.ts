import { expect, test } from '@playwright/test'
import { navigate } from './helpers'

test('V2 rewards, difficulty and apply/edit workflows fit the requested viewports', async ({page},info) => {
  test.setTimeout(120000)
  for (const [width,height] of info.project.name==='mobile' ? [[390,844]] : [[768,1024],[1366,768],[1440,900]]) {
    await page.setViewportSize({width,height});await page.goto('./')
    await navigate(page,'editor');await navigate(page,'presets')
    const gallery=page.locator('#preset-panel')
    await gallery.getByRole('tab',{name:/매우 어려움/}).click()
    await expect(gallery.locator('.gallery-thumbnails > button')).toHaveCount(6)
    await gallery.getByTestId('preset-30_the_endless_labyrinth').click()
    await expect(gallery).not.toContainText('극악')
    await page.screenshot({path:info.outputPath(`v2-gallery-${width}x${height}.png`),animations:'disabled'})
    page.once('dialog',d=>d.dismiss());await gallery.getByRole('button',{name:'맵 적용하기',exact:true}).click()
    await expect(gallery).toBeVisible();await expect(page.getByTestId('nav-editor')).toHaveAttribute('aria-current','page')
    page.once('dialog',d=>d.accept());await gallery.getByRole('button',{name:'맵 적용하기',exact:true}).click()
    await expect(gallery).toBeHidden();await expect(page.getByTestId('nav-environment')).toHaveAttribute('aria-current','page')
    await expect(page.getByTestId('environment-applied')).toContainText('맵이 적용되었습니다.')
    const grid=page.getByTestId('learning-grid')
    await expect(grid.getByTestId('grid-svg')).toHaveAttribute('viewBox','0 0 2304 1920')
    await navigate(page,'presets');await page.getByTestId('preset-01_meadow_walk').click()
    await page.getByRole('button',{name:'편집기로 불러오기',exact:true}).click()
    await expect(page.getByTestId('nav-editor')).toHaveAttribute('aria-current','page')
    await expect(grid.getByTestId('grid-svg')).toHaveAttribute('viewBox','0 0 2304 1920')
    await expect(page.getByTestId('env-editor').getByTestId('grid-svg')).toHaveAttribute('viewBox','0 0 384 384')
    await navigate(page,'presets');await page.getByTestId('preset-01_meadow_walk').click()
    page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'맵 적용하기',exact:true}).click()
    await page.getByRole('button',{name:'설정',exact:true}).click()
    await page.getByRole('tab',{name:'시각화 설정',exact:true}).click()
    await page.getByTestId('toggle-live-rewards').check();await page.getByTestId('toggle-rewards').check();await page.getByTestId('toggle-reward-animation').check()
    await page.screenshot({path:info.outputPath(`v2-settings-${width}x${height}.png`),animations:'disabled'})
    await page.getByRole('button',{name:'설정',exact:true}).click()
    await page.getByTestId('speed-slider').fill('90')
    await page.getByTestId('playback-run-greedy').click();await expect(page.getByTestId('speed-slider')).toHaveValue('45')
    await page.getByTestId('playback-pause').click()
    await expect(page.getByTestId('last-reward')).not.toHaveText('—')
    await page.getByTestId('speed-slider').fill('60');await expect(page.getByTestId('speed-slider')).toHaveValue('60')
    expect(await page.getByTestId('reward-animation').count()).toBeLessThanOrEqual(1)
    await page.screenshot({path:info.outputPath(`v2-rewards-${width}x${height}.png`),animations:'disabled'})
    await page.getByTestId('playback-stop').click();await expect(page.getByTestId('speed-slider')).toHaveValue('90')
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
  }
})
