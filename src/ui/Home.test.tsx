// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import App from './App'
import { engine } from './engine'
import { createDefaultGridWorldConfig } from '../core/environments/gridworld/GridWorldEnv'

beforeEach(() => {
  vi.useFakeTimers()
  engine.reset({ envConfig: createDefaultGridWorldConfig(), algorithmId: 'q-learning' })
  engine.setSpeed({ mode: 'interval', intervalMs: 100000 })
})
afterEach(() => { cleanup(); engine.reset(); vi.useRealTimers(); vi.restoreAllMocks() })
const live = () => within(screen.getByTestId('learning-grid'))

describe('Fullscreen workspace', () => {
  it('starts on the Korean home with an explicitly scripted, automatically playing demo', () => {
    render(<App />)
    expect(screen.getByRole('heading', { level: 1 }).textContent).toBe('강화학습 시뮬레이터')
    expect(screen.getByTestId('experiment-workspace').hidden).toBe(true)
    expect(screen.getByText(/실제 학습 결과가 아닙니다/)).toBeTruthy()
    expect(screen.getByTestId('nav-home').getAttribute('aria-current')).toBe('page')
    act(() => vi.advanceTimersByTime(600))
    expect(screen.getByRole('img').getAttribute('aria-label')).toContain('1번 이동')
    expect(engine.getSnapshot().lastTransition).toBeNull()
  })
  it('uses default-on overlays and removes Step/Reset while preserving running data through navigation and panels', () => {
    render(<App />)
    fireEvent.click(screen.getByTestId('nav-environment'))
    expect(screen.queryByTestId('playback-step')).toBeNull()
    expect(screen.queryByTestId('playback-reset')).toBeNull()
    expect((screen.getByTestId('toggle-policy') as HTMLInputElement).checked).toBe(true)
    expect((screen.getByTestId('toggle-value') as HTMLInputElement).checked).toBe(true)
    fireEvent.click(live().getByTestId('cell-1,1'))
    fireEvent.click(screen.getByTestId('playback-run-episode'))
    const before = engine.getSnapshot()
    fireEvent.click(screen.getByTestId('toggle-analysis'))
    const values = screen.getByTestId('qvalue-bars')
    fireEvent.click(screen.getByTestId('toggle-analysis'))
    expect(screen.getByTestId('analysis-panel').hidden).toBe(true)
    fireEvent.click(screen.getByTestId('nav-home'))
    fireEvent.click(screen.getByTestId('nav-results'))
    expect(screen.getByTestId('analysis-panel').hidden).toBe(false)
    expect(screen.getByTestId('qvalue-bars')).toBe(values)
    expect(values.textContent).toContain('1,1')
    expect(engine.getSnapshot()).toEqual(before)
    fireEvent.click(screen.getByTestId('nav-environment'))
    fireEvent.click(screen.getByTestId('playback-stop'))
    expect(engine.getSnapshot().status).toBe('idle')
    expect(engine.getSnapshot().agentSnapshot).toEqual(before.agentSnapshot)
    expect(engine.getSnapshot().stats.episodeStatsHistory).toEqual(before.stats.episodeStatsHistory)
  })
  it('preserves editor drafts, selection and reward values through independent screens and locale changes', () => {
    render(<App />)
    fireEvent.click(screen.getByTestId('nav-editor'))
    const editor = screen.getByTestId('env-editor')
    fireEvent.click(within(editor).getByTestId('env-editor-mode-wall'))
    fireEvent.click(within(editor).getByTestId('cell-2,2'))
    fireEvent.click(within(editor).getByTestId('env-editor-mode-wall'))
    fireEvent.click(within(editor).getByTestId('cell-3,3'))
    const before = engine.getSnapshot()
    fireEvent.click(screen.getByTestId('nav-home'))
    fireEvent.change(screen.getAllByTestId('language-selector')[0], { target: { value: 'en' } })
    fireEvent.click(screen.getByTestId('nav-editor'))
    expect(screen.getByTestId('env-editor')).toBe(editor)
    expect(within(editor).getByTestId('cell-2,2').getAttribute('data-cell-kind')).toBe('wall')
    expect(within(editor).getByTestId('cell-3,3').getAttribute('data-cell-kind')).toBe('wall')
    expect(engine.getSnapshot()).toEqual(before)
    expect(document.documentElement.lang).toBe('en')
  })
  it('preserves episode selection and the trajectory panel through open/close', () => {
    engine.reset({ envConfig: { ...createDefaultGridWorldConfig(), width: 3, height: 3, start: { x: 0, y: 1 }, goals: [{ x: 0, y: 0 }] }, hyperparams: { alpha: 0.1, gamma: 0.9, epsilon: 0 } })
    engine.setSpeed({ mode: 'batch', stepsPerFrame: 100 })
    render(<App />)
    fireEvent.click(screen.getByTestId('nav-environment'))
    fireEvent.change(screen.getByTestId('episode-count-input'), { target: { value: '2' } })
    fireEvent.click(screen.getByTestId('playback-run-episode'))
    fireEvent.click(screen.getByTestId('toggle-analysis'))
    fireEvent.click(screen.getByTestId('episode-history-row-1'))
    const trajectory = screen.getByTestId('episode-trajectory')
    fireEvent.click(screen.getByTestId('toggle-analysis'))
    fireEvent.click(screen.getByTestId('toggle-analysis'))
    expect(screen.getByTestId('episode-trajectory')).toBe(trajectory)
    expect(screen.getByTestId('episode-history-row-1').getAttribute('data-selected')).toBe('true')
  })
  it('follows a new live map while pristine and retains unsaved draft edits after later live-map changes', () => {
    render(<App />)
    act(() => engine.reset({ envConfig: { ...createDefaultGridWorldConfig(), width: 3, height: 3, goals: [{ x: 2, y: 2 }] } }))
    fireEvent.click(screen.getByTestId('nav-editor'))
    expect((screen.getByTestId('env-editor-width-input') as HTMLInputElement).value).toBe('3')
    const editor = screen.getByTestId('env-editor')
    fireEvent.click(within(editor).getByTestId('cell-1,1'))
    act(() => engine.reset({ envConfig: createDefaultGridWorldConfig() }))
    expect((screen.getByTestId('env-editor-width-input') as HTMLInputElement).value).toBe('3')
    expect(within(editor).getByTestId('cell-1,1').getAttribute('data-cell-kind')).toBe('wall')
  })
  it('closes the mobile drawer with Escape and restores focus', () => {
    render(<App />)
    fireEvent.click(document.getElementById('mobile-menu')!)
    expect(document.querySelector('.workspace')?.hasAttribute('inert')).toBe(true)
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(document.getElementById('mobile-menu')?.getAttribute('aria-expanded')).toBe('false')
    expect(document.activeElement?.id).toBe('mobile-menu')
  })
  it('does not reset the experiment while previewing presets or cancelling apply', () => {
    render(<App />)
    fireEvent.click(screen.getByTestId('nav-environment'))
    const before = engine.getSnapshot()
    fireEvent.click(screen.getByTestId('nav-presets'))
    fireEvent.click(screen.getByTestId('preset-maze'))
    expect(engine.getSnapshot()).toEqual(before)
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    fireEvent.click(screen.getByRole('button', { name: /^맵 적용$/ }))
    expect(engine.getSnapshot()).toEqual(before)
  })
})

describe('Home demonstration lifecycle', () => {
  it('loops, pauses, compares paths without touching the real engine and cleans up on navigation', () => {
    const clear = vi.spyOn(window, 'clearInterval')
    render(<App />)
    const before = engine.getSnapshot()
    act(() => vi.advanceTimersByTime(600 * 20))
    expect(screen.getByRole('img').getAttribute('aria-label')).toContain('0번 이동')
    fireEvent.click(screen.getByRole('button', { name: '일시정지' }))
    act(() => vi.advanceTimersByTime(1200))
    expect(screen.getByRole('img').getAttribute('aria-label')).toContain('0번 이동')
    fireEvent.click(screen.getByRole('button', { name: '학습 후 · 경로 활용' }))
    for (let i = 0; i < 9; i++) fireEvent.click(screen.getByRole('button', { name: '한 칸 이동' }))
    expect(screen.getByRole('img').getAttribute('aria-label')).toContain('9번 이동')
    expect(engine.getSnapshot()).toEqual(before)
    fireEvent.click(screen.getByRole('button', { name: '시연 재생' }))
    fireEvent.click(screen.getByTestId('nav-environment'))
    expect(clear).toHaveBeenCalled()
    expect(vi.getTimerCount()).toBeLessThanOrEqual(1)
  })
  it('starts paused when reduced motion is requested', () => {
    vi.stubGlobal('matchMedia', () => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
    render(<App />)
    expect(screen.getByRole('button', { name: '시연 재생' })).toBeTruthy()
    act(() => vi.advanceTimersByTime(6000))
    expect(screen.getByRole('img').getAttribute('aria-label')).toContain('0번 이동')
    vi.unstubAllGlobals()
  })
})
